"""Generate searchable metadata and optional TS parameter-key hints. No actions are executed.
Usage: python3 scripts/generate-catalog.py [/path/to/toolkit-v78-first-party-parameter-keys.json]
Without a snapshot argument, regenerate from the checked-in metadata.
The input schema is the Shortcuts Playground ToolKit parameter snapshot format.
"""
import json
from pathlib import Path
import sys
from action_functions import assign_functions

root = Path(__file__).resolve().parent.parent
if len(sys.argv) > 1:
    snapshot = json.loads(Path(sys.argv[1]).read_text())
    actions = []
    for identifier, tool in sorted(snapshot['tools'].items()):
        actions.append({
            'id': identifier,
            'name': tool.get('displayName', identifier),
            'platforms': tool.get('platforms', []),
            'parameters': [{
                'key': p['key'], 'type': p.get('typePythonName', 'unknown'),
                **({'name': p['name']} if 'name' in p else {})
            } for p in tool.get('parameters', [])]
        })
    catalog = {
        'source': 'https://github.com/viticci/shortcuts-playground-plugin/blob/main/codex/skills/shortcuts-playground/data/toolkit-v78-first-party-parameter-keys.json',
        'version': 'ToolKit v78; iOS 27 Simulator and macOS 27; snapshot ' + snapshot.get('generated_at', 'unknown'),
        'notice': 'Metadata only. Entries may be platform-specific, internal, unavailable or require additional app-intent configuration. Not an execution guarantee. Unknown app IDs remain usable through native().',
        'actions': actions,
    }
else:
    catalog = json.loads((root / 'data/actions.json').read_text())
    actions = sorted(catalog['actions'], key=lambda action: action['id'])
    catalog['actions'] = actions
assign_functions(actions)
(root / 'data/actions.json').write_text(json.dumps(catalog, indent=2, ensure_ascii=False) + '\n')
lines = ['// Generated by scripts/generate-catalog.py. Parameter KEY hints, not validated value schemas.',
         'declare module "@js-shortcuts/ios" {', '  export interface KnownNativeParameters {']
for action in actions:
    keys = sorted(set(p['key'] for p in action['parameters']) | {'UUID', 'CustomOutputName'})
    lines.append(f'    {json.dumps(action["id"])}: {{ ' + ' '.join(f'{json.dumps(k)}?: NativeParameter;' for k in keys) + ' };')
lines += ['  }', '  export type KnownNativeAction = keyof KnownNativeParameters;',
          '  export type NativeActionParameters<K extends string> = K extends KnownNativeAction ? KnownNativeParameters[K] : NativeParameters;', '}']
(root / 'api/actions.generated.d.ts').write_text('\n'.join(lines) + '\n')
lines = ['// Generated by scripts/generate-catalog.py. Do not edit.',
         '// Native parameter-key hints; result defaults declare expectations, not runtime validation.',
         'declare module "@js-shortcuts/ios" {']
categories = sorted(set(action['category'] for action in actions))
for category in categories:
    lines += [f'  /** Native {category} actions. Call directly with await; parameter keys use native spelling. */',
              f'  export const {category}: {{']
    for action in sorted((a for a in actions if a['category'] == category), key=lambda a: a['functionName']):
        doc = f'{action["name"]} — {action["id"]}'.replace('*/', '* /').replace('\n', ' ').replace('\r', ' ')
        optional = '?' if not action['parameters'] else ''
        result = action.get('resultType', 'NativeContent')
        lines += [f'    /** {doc} */',
                  f'    readonly {action["functionName"]}: <T = {result}>(parameters{optional}: KnownNativeParameters[{json.dumps(action["id"])}] | NativeEncoded) => Promise<T>;']
    lines.append('  };')
lines.append('}')
(root / 'api/functions.generated.d.ts').write_text('\n'.join(lines) + '\n')
print(f'Generated {len(actions)} action entries in {len(categories)} categories.')

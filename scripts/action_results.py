"""TypeScript output declarations from the checked-in Apple output schema snapshot."""
import json

PRIMITIVES = {'none': 'void', 'bool': 'boolean', 'int': 'number', 'number': 'number',
              'decimal': 'number', 'string': 'string', 'character': 'string'}
ORIENTATION = 'com.apple.ShortcutsActions.Orientation'
LLM = 'is.workflow.actions.askllm'


def render(schema, types):
    kind = schema['kind']
    if kind == 'array':
        return f'Array<{render(schema["element"], types)}>'
    if kind == 'union':
        return ' | '.join(sorted(set(render(member, types) for member in schema['members'])))
    identifier = schema['id']
    if identifier in PRIMITIVES:
        return PRIMITIVES[identifier]
    definition = types[identifier]
    if identifier == ORIENTATION:
        return 'DeviceOrientation'
    if definition.get('cases'):
        return f'NativeEnumValues[{json.dumps(identifier)}]'
    if identifier == 'com.apple.shortcuts.WFContentItem':
        return 'NativeContent'
    return f'NativeEntity<{json.dumps(identifier)}>'


def comment(text):
    return text.replace('*/', '* /').replace('\n', ' ').replace('\r', ' ')


def result_for(action, snapshot):
    entry = snapshot['actions'].get(action['id'], {'status': 'unresolved'})
    if entry['status'] != 'known':
        return f'UnresolvedActionResult<{json.dumps(action["id"])}>'
    return render(entry['schema'], snapshot['types'])


def declarations(actions, snapshot):
    lines = ['// Generated by scripts/generate-catalog.py from data/action-results.json.',
             'declare module "@js-shortcuts/ios" {',
             '  /** An Apple native entity. Pass it to native actions; it is not a JavaScript object. */',
             '  export interface NativeEntity<Identifier extends string> extends NativeContent { readonly __nativeType: Identifier }',
             '  /** No output schema was found for this catalog entry. Not a claim about its return type. */',
             '  export interface UnresolvedActionResult<Identifier extends string> extends NativeContent { readonly __unresolvedAction: Identifier }',
             '  /** English display values from Apple AppEnum metadata, as used by native text coercion. */',
             '  export interface NativeEnumValues {']
    for identifier, definition in snapshot['types'].items():
        if definition.get('cases'):
            values = sorted(set(case['title'] for case in definition['cases'] if case['title'] is not None))
            lines.append(f'    {json.dumps(identifier)}: ' + ' | '.join(json.dumps(value) for value in values) + ';')
    lines += ['  }',
              '  /** Native case identifiers by English title, for enum conditions (WFLinkEnumeration).',
              '   * Enums whose titles are missing or not unique are omitted. */',
              '  export interface NativeEnumCases {']
    for identifier, definition in snapshot['types'].items():
        cases = definition.get('cases') or []
        titles = [case['title'] for case in cases]
        if cases and None not in titles and len(set(titles)) == len(titles):
            fields = ' '.join(f'{json.dumps(case["title"])}: {json.dumps(case["id"])};' for case in cases)
            lines.append(f'    {json.dumps(identifier)}: {{ {fields} }};')
    lines += ['  }',
              '  /** Static App Entity property declarations (identifier: value type) from Apple metadata.',
              '   * Read with entityProperty(entity, "identifier"); titles are English display names. */',
              '  export interface NativeEntityProperties {']
    for identifier, definition in snapshot['types'].items():
        if definition.get('properties'):
            fields = ' '.join(f'/** {comment(item["title"] or item["id"])}{" (optional; may be empty)" if item.get("optional") else ""} */ {json.dumps(item["id"])}: {render(item["schema"], snapshot["types"])};'
                              for item in definition['properties'])
            lines.append(f'    {json.dumps(identifier)}: {{ {fields} }};')
    lines += ['  }', f'  export type DeviceOrientation = NativeEnumValues[{json.dumps(ORIENTATION)}];',
              '  export interface KnownNativeResults {']
    for action in actions:
        lines.append(f'    {json.dumps(action["id"])}: {result_for(action, snapshot)};')
    lines += ['  }', '  export type NativeActionResult<K extends KnownNativeAction> = KnownNativeResults[K];', '}']
    return '\n'.join(lines) + '\n'
